-- ## 验收标准 3 的语料设计（**刻意的漏召回**）
--
-- 验收标准 3 要求：用「邮费是多少」去问，关键词查表**查不出来**。
--
-- 所以下面这份 FAQ 语料**刻意不含「邮费」二字**，同时保留了
-- 「退货运费谁承担？」「满多少包邮？」这类语义相关但用词不同的条目。
-- 于是 `LIKE '%邮费%'` 必然命中 0 条 —— 漏召回稳定可复现，
-- 这就是留给 ch03 做向量检索改造的「改造前基线」。
--
-- 也**必须**保持全表不含「邮费」二字（包括答案字段）：只要有一处出现，
-- 验收标准 3 就不再成立，而这个改动很容易在后续加语料时被无意破坏。
-- 将来若要测「工具不会假命中」，需要单独造一份含该词的语料，
-- 不能直接往这份基线语料里加 —— 那会毁掉基线。
--
-- 中文 ENUM 值/字符串要按 utf8mb4 解析，否则 latin1 客户端会 double-encode。
SET NAMES utf8mb4;

